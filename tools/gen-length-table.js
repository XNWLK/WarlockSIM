// Round 166 (user: "create a sheet with a table breaking down the builds by race and time frame. (60s/120s/180s/240s/300s"):
// every built-in build × race (and "No race") × fight length, default settings otherwise, written to
// data/length-table.js for the "By fight length" sheet on the page. The page shows it as it is for the default settings
// and can redo it with your own settings. Like the default results, the file records the SHA-256 of every engine / data
// file it was made from; tests/test-round166.js fails when one changed since — then run this again:
//   node tools/gen-length-table.js            (from the project root; uses every CPU core)
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const fs = require('fs'), path = require('path'), crypto = require('crypto'), os = require('os');
const { load, SOURCE_FILES } = require('./load-wl.js');
const root = path.resolve(__dirname, '..');
const DURATIONS = [60, 120, 180, 240, 300];

if (!isMainThread) {
  const WL = load(workerData.root);
  parentPort.on('message', j => {
    const cfg = JSON.parse(JSON.stringify(WL.DEFAULT_CONFIG)); cfg.fight.duration = j.d;
    const b = WL.BUILDS.find(x => x.key === j.key);
    parentPort.postMessage({ i: j.i, dps: WL.simulate(b, j.race, cfg).dps });
  });
  return;
}

const WL = load(root), cfg = WL.DEFAULT_CONFIG;
const builtins = WL.BUILDS.filter(b => !b.custom);
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n')).digest('hex');
function runJobs(jobs) {
  const n = Math.max(1, Math.min(jobs.length, os.cpus().length)), out = new Array(jobs.length);
  return new Promise(resolve => {
    let next = 0, left = jobs.length; const pool = [];
    for (let k = 0; k < n; k++) {
      const w = new Worker(__filename, { workerData: { root } });
      w.on('message', m => { out[m.i] = m.dps; if (--left === 0) { pool.forEach(x => x.terminate()); resolve(out); } else if (next < jobs.length) w.postMessage(jobs[next++]); });
      pool.push(w);
    }
    pool.forEach(w => { if (next < jobs.length) w.postMessage(jobs[next++]); });
  });
}
(async () => {
  const t0 = Date.now(), jobs = [];
  builtins.forEach(b => WL.SIM_RACE_KEYS.forEach(race => DURATIONS.forEach(d => jobs.push({ key: b.key, race, d, i: jobs.length }))));
  const dps = await runJobs(jobs);
  const rows = [];
  builtins.forEach(b => WL.SIM_RACE_KEYS.forEach(race => {
    rows.push({ build: b.key, race, dps: DURATIONS.map(d => Math.round(10 * dps[jobs.find(j => j.key === b.key && j.race === race && j.d === d).i]) / 10) });
  }));
  const src = {}; SOURCE_FILES.forEach(f => { src[f] = hash(f); });
  const out = { generated: new Date().toISOString().slice(0, 10), src, durations: DURATIONS, iterations: cfg.fight.iterations, varPct: cfg.fight.durationVarPct, seed: cfg.fight.seed, rows };
  const file = path.join(root, 'data/length-table.js');
  fs.writeFileSync(file, '// Generated by tools/gen-length-table.js — do not edit by hand (round 166). DPS of every built-in build and race by\n' +
    '// fight length, default settings otherwise (' + cfg.fight.iterations + ' fights each, ±' + cfg.fight.durationVarPct + '%).\nwindow.WL = window.WL || {};\nWL.LENGTH_TABLE = ' + JSON.stringify(out) + ';\n');
  console.log('data/length-table.js: ' + rows.length + ' rows × ' + DURATIONS.length + ' lengths (' + jobs.length + ' runs) in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
})();
