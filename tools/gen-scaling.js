// Round 189 (user: "make this setup the default so people see this when they go to the sim"): the Build Scaling chart for
// the default settings, shipped with the page (data/default-scaling.js) so it shows at once on a first visit — every
// built-in build with the race it is listed with (its best race in data/default-results.js), gear levels 0 … 7 of the
// chart's default top level (CH_SCALE_DEF in app/app.js), cfg.fight.iterations fights per point. The same jobs as the
// page's "Draw chart" (WL.statWeightRun with the level's sheet values), so the numbers are identical. Like the other
// generated files it records the SHA-256 of every engine / data file; tests/test-round189.js fails when one changed — run
//   node tools/gen-scaling.js        (from the project root; gen-default-results.js runs it too)
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const fs = require('fs'), path = require('path'), crypto = require('crypto'), os = require('os'), vm = require('vm');
const { load, SOURCE_FILES } = require('./load-wl.js');
const root = path.resolve(__dirname, '..');

// The chart's own rule (app/app.js scaleGear): a level's sheet values; hit / crit / haste to 2 decimals, the rest whole.
function scaleGear(lv, def) {
  const f = lv / def.levels, o = {};
  Object.keys(def.max).forEach(k => { if ((k === 'int' || k === 'spi') && !def.intSpi) return; o[k] = +(def.max[k] * f).toFixed(k === 'hitPct' || k === 'critPct' || k === 'hastePct' ? 2 : 0); });
  return o;
}

if (!isMainThread) {
  const WL = load(workerData.root);
  parentPort.on('message', j => {
    const cfg = JSON.parse(JSON.stringify(WL.DEFAULT_CONFIG)); Object.assign(cfg.gear, scaleGear(j.lv, j.def));
    const b = WL.BUILDS.find(x => x.key === j.key);
    parentPort.postMessage({ i: j.i, dps: WL.statWeightRun(b, j.race, cfg, cfg.fight.iterations, null) });
  });
  return;
}

const WL = load(root, ['engine/settings-code.js']), cfg = WL.DEFAULT_CONFIG;
const builtins = WL.BUILDS.filter(b => !b.custom);
const app = fs.readFileSync(path.join(root, 'app/app.js'), 'utf8');
const m = /var CH_SCALE_DEF = (\{[^;]*\});/.exec(app);
if (!m) throw new Error('CH_SCALE_DEF not found in app/app.js');
const DEF = JSON.parse(m[1].replace(/'/g, '"').replace(/(\w+):/g, '"$1":'));
const ctx = { window: {} }; ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data/default-results.js'), 'utf8'), ctx);
const D = ctx.WL.DEFAULT_RESULTS;
const raceOf = key => D.results.filter((r, i) => D.keys[i] === key && r.race !== WL.BASELINE_RACE).sort((a, z) => z.dps - a.dps)[0].race;
const snap = WL.settingsSnapshot(cfg); snap.options = Object.assign({}, snap.options); delete snap.options.showWithinPct;   // = app.js snapNoCut
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n')).digest('hex');

(async () => {
  const t0 = Date.now(), xs = [], jobs = [];
  for (let lv = 0; lv <= DEF.levels; lv++) xs.push(lv);
  const series = builtins.map(b => ({ key: b.key, race: raceOf(b.key), y: [] }));
  series.forEach((s, si) => xs.forEach((lv, xi) => jobs.push({ i: jobs.length, si, xi, key: s.key, race: s.race, lv, def: DEF })));
  const out = new Array(jobs.length);
  await new Promise(resolve => {
    const n = Math.max(1, Math.min(jobs.length, os.cpus().length)); let next = 0, left = jobs.length; const pool = [];
    for (let k = 0; k < n; k++) {
      const w = new Worker(__filename, { workerData: { root } });
      w.on('message', r => { out[r.i] = r.dps; if (--left === 0) { pool.forEach(x => x.terminate()); resolve(); } else if (next < jobs.length) w.postMessage(jobs[next++]); });
      pool.push(w);
    }
    pool.forEach(w => { if (next < jobs.length) w.postMessage(jobs[next++]); });
  });
  jobs.forEach(j => { series[j.si].y[j.xi] = out[j.i]; });
  const src = {}; SOURCE_FILES.forEach(f => { src[f] = hash(f); });
  const file = { generated: new Date().toISOString().slice(0, 10), src, settings: JSON.stringify(snap), builds: JSON.stringify(builtins), def: DEF, xs, n: cfg.fight.iterations, series };
  const js = '// Generated by tools/gen-scaling.js — do not edit by hand (round 189). The Build Scaling chart for the default settings,\n' +
    '// shown on a first visit; see the tool for how it is made and checked.\n' +
    'window.WL = window.WL || {};\nWL.DEFAULT_SCALING = ' + JSON.stringify(file) + ';\n';
  fs.writeFileSync(path.join(root, 'data/default-scaling.js'), js);
  console.log('data/default-scaling.js: ' + series.length + ' builds × ' + xs.length + ' levels × ' + cfg.fight.iterations + ' fights in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
})();
