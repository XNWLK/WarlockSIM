// Round 76 (performance): simulate the default settings once and write data/default-results.js, so a first visit shows
// the results table at once instead of simulating ~169,000 fights. The page uses the file only when its settings and
// built-in builds are exactly the ones below; the tests (test-round76.js) fail when any engine / data file changed
// since (SHA-256 of each file, line endings ignored) or a re-simulation differs — then run this again:
//   node tools/gen-default-results.js            (from the project root; uses every CPU core)
// Same jobs, order and best-race rule as a run on the page (app/app.js run()): every built-in build × WL.SIM_RACE_KEYS,
// then stat weights on each build's best real race.
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const fs = require('fs'), path = require('path'), crypto = require('crypto'), os = require('os');
const { load, SOURCE_FILES } = require('./load-wl.js');
const root = path.resolve(__dirname, '..');

if (!isMainThread) {                                  // one thread: load the engine, run the jobs it is given
  const WL = load(workerData.root), cfg = WL.DEFAULT_CONFIG;
  parentPort.on('message', j => {
    const b = WL.BUILDS.find(x => x.key === j.key);
    parentPort.postMessage(j.kind === 'combo' ? { i: j.i, r: WL.stripResult(WL.simulate(b, j.race, cfg)) }
      : { i: j.i, dps: WL.statWeightRun(b, j.race, cfg, cfg.fight.weightIterations, j.stat) });
  });
  return;
}

const WL = load(root, ['engine/settings-code.js']), cfg = WL.DEFAULT_CONFIG;
const builtins = WL.BUILDS.filter(b => !b.custom);
const snap = WL.settingsSnapshot(cfg); snap.options = Object.assign({}, snap.options); delete snap.options.showWithinPct;   // = app.js snapNoCut
const hash = f => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n')).digest('hex');

function runJobs(jobs) {
  const n = Math.max(1, Math.min(jobs.length, os.cpus().length)), out = new Array(jobs.length);
  return new Promise(resolve => {
    let next = 0, left = jobs.length;
    const pool = [];
    for (let k = 0; k < n; k++) {
      const w = new Worker(__filename, { workerData: { root } });
      w.on('message', m => { out[m.i] = m; if (--left === 0) { pool.forEach(x => x.terminate()); resolve(out); } else if (next < jobs.length) w.postMessage(jobs[next++]); });
      pool.push(w);
    }
    pool.forEach(w => { if (next < jobs.length) w.postMessage(jobs[next++]); });
  });
}

(async () => {
  const t0 = Date.now();
  const combos = [];
  builtins.forEach(b => WL.SIM_RACE_KEYS.forEach(race => combos.push({ kind: 'combo', key: b.key, race, i: combos.length })));
  const results = (await runJobs(combos)).map(m => m.r);
  console.log(combos.length + ' combos in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  const wj = [];
  builtins.forEach(b => {                              // best real race (the page: bestRow — highest DPS, stable order)
    const best = results.filter((r, i) => combos[i].key === b.key && r.race !== WL.BASELINE_RACE).sort((x, y) => y.dps - x.dps)[0];
    // Round 79: the unchanged base run = the best-race combo (same fights) when both use the same number of fights.
    const stats = cfg.fight.weightIterations === cfg.fight.iterations ? WL.STAT_WEIGHT_KEYS : [null].concat(WL.STAT_WEIGHT_KEYS);
    stats.forEach(stat => wj.push({ kind: 'weight', key: b.key, race: best.race, stat, base: best.dps, i: wj.length }));
  });
  const wr = await runJobs(wj), weights = {};
  builtins.forEach(b => {
    const mine = wj.filter(j => j.key === b.key), by = {};
    const base = mine[0].stat === null ? wr[mine[0].i].dps : mine[0].base;
    mine.filter(j => j.stat).forEach(j => { by[j.stat] = wr[j.i].dps; });
    weights[b.key] = { race: mine[0].race, w: WL.combineWeights(cfg, base, by) };
  });
  // Self-check for the page: DPS of fight #1 of every row. The page re-simulates these 78 single fights (~0.1 s) and uses
  // the file only if all match exactly — a changed engine or a browser with other floating-point results → live run.
  const probe = combos.map(c => WL.firstFight(WL.BUILDS.find(x => x.key === c.key), c.race, cfg).dps);
  const src = {}; SOURCE_FILES.forEach(f => { src[f] = hash(f); });
  const file = {
    generated: new Date().toISOString().slice(0, 10), src,
    settings: JSON.stringify(snap), builds: JSON.stringify(builtins),
    keys: combos.map(c => c.key), results, weights, probe,
  };
  const js = '// Generated by tools/gen-default-results.js — do not edit by hand (round 76). The default results: the page shows\n' +
    '// them on a first visit when its settings and built-in builds match; see the tool for how they are checked.\n' +
    'window.WL = window.WL || {};\nWL.DEFAULT_RESULTS = ' + JSON.stringify(file) + ';\n';
  fs.writeFileSync(path.join(root, 'data/default-results.js'), js);
  console.log('data/default-results.js: ' + (js.length / 1024).toFixed(0) + ' KB, ' + results.length + ' results + ' + Object.keys(weights).length +
    ' stat weights in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
})();
